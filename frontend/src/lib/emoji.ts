/** Every emoji whose name contains each word of `query`, or all of `items` for an empty query. */
export function searchEmoji(query: string): [string, string][] {
  const words = query.toLowerCase().split(/\s+/).filter(Boolean);
  const all = EMOJI_GROUPS.flatMap((g) => g.items);
  return words.length ? all.filter(([, name]) => words.every((w) => name.includes(w))) : all;
}
